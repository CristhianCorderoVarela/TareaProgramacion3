DECLARE
  v_max  NUMBER := 0;
  v_curr NUMBER;
BEGIN
  SELECT GREATEST(
           NVL((SELECT MAX(ID) FROM ADMINISTRADORES), 0),
           NVL((SELECT MAX(ID) FROM PROYECTOS), 0),
           NVL((SELECT MAX(ID) FROM ACTIVIDADES), 0),
           NVL((SELECT MAX(ID) FROM SEGUIMIENTO_PROYECTO), 0)
         ) + 1
    INTO v_max
    FROM DUAL;

  BEGIN
    SELECT SEQ_GEN_IDENTITY.CURRVAL INTO v_curr FROM DUAL;
  EXCEPTION WHEN OTHERS THEN
    SELECT SEQ_GEN_IDENTITY.NEXTVAL INTO v_curr FROM DUAL;
  END;

  IF v_curr < v_max THEN
    EXECUTE IMMEDIATE 'ALTER SEQUENCE SEQ_GEN_IDENTITY INCREMENT BY '||(v_max - v_curr);
    SELECT SEQ_GEN_IDENTITY.NEXTVAL INTO v_curr FROM DUAL; -- aplica el salto
    EXECUTE IMMEDIATE 'ALTER SEQUENCE SEQ_GEN_IDENTITY INCREMENT BY 1';
  END IF;
END;
/

