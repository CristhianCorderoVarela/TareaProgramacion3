CREATE OR REPLACE TRIGGER TRG_ADMINISTRADOR_ID
BEFORE INSERT ON ADMINISTRADORES
FOR EACH ROW
BEGIN
  IF :NEW.ID IS NULL THEN :NEW.ID := SEQ_ADMINISTRADOR_ID.NEXTVAL; END IF;
END;
